import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { cyan, green, yellow } from "kleur/colors";
import { ensureDirectory, parseArgs, writeFileSafe } from "../lib/fs.js";
import { promptBoolean, promptText } from "../lib/prompt.js";
import { detectRepoConfig } from "../lib/repo.js";
import { renderFastfile, renderGemfile, renderGitHubWorkflow, renderReadme } from "../templates/android.js";

export async function runInitCommand(argv: string[]): Promise<void> {
  const args = parseArgs(argv);
  const target = path.resolve(args.target ?? process.cwd());
  const config = await detectRepoConfig(target);
  const isInteractive = args["no-prompt"] !== "true";
  const androidProjectPath = args["android-project-path"] ?? "android";
  const androidApplicationId = args["android-application-id"]
    ?? (isInteractive
      ? await promptText("Android application id", { defaultValue: "com.example.app", required: true })
      : "com.example.app");
  const enablePlayDeploy = args["enable-play-deploy"]
    ? args["enable-play-deploy"] !== "false"
    : isInteractive
      ? await promptBoolean("Enable Google Play production upload", true)
      : true;

  console.log(cyan(`Target: ${target}`));
  console.log(cyan("The Android project will be generated by Expo prebuild in CI."));

  await ensureDirectory(config.workflowDir);
  await ensureDirectory(config.infraDir);
  await writeFileSafe(
    path.join(config.workflowDir, "android-ci.yml"),
    renderGitHubWorkflow({
      androidProjectPath,
      androidApplicationId,
      enablePlayDeploy,
    }),
  );

  await writeFileSafe(
    path.join(config.infraDir, "README.md"),
    renderReadme({
      androidProjectPath,
      androidApplicationId,
      enablePlayDeploy,
    }),
  );

  const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
  const scriptsDir = path.join(target, "scripts");
  const helpersDir = path.join(config.infraDir, "scripts");
  await ensureDirectory(scriptsDir);
  await ensureDirectory(helpersDir);

  const fs = await import("node:fs/promises");
  for (const filename of ["encode-secrets.sh", "encode-secrets.ps1"]) {
    await fs.copyFile(
      path.join(packageRoot, "scripts", filename),
      path.join(helpersDir, filename),
    );
  }
  await fs.copyFile(
    path.join(packageRoot, "scripts", "patch-android-release-signing.mjs"),
    path.join(scriptsDir, "patch-android-release-signing.mjs"),
  );

  if (enablePlayDeploy) {
    const fastlaneDir = path.join(target, "fastlane");
    await ensureDirectory(fastlaneDir);
    const fastfilePath = path.join(fastlaneDir, "Fastfile");
    const gemfilePath = path.join(target, "Gemfile");
    try {
      await fs.access(fastfilePath);
      console.log(yellow("Root fastlane/Fastfile already exists; leaving it unchanged."));
    } catch {
      await writeFileSafe(fastfilePath, renderFastfile({ androidApplicationId, enableSentry: false }));
      console.log(green("Generated fastlane/Fastfile at the repository root."));
    }
    try {
      await fs.access(gemfilePath);
      console.log(yellow("Root Gemfile already exists; leaving it unchanged."));
    } catch {
      await writeFileSafe(gemfilePath, renderGemfile());
      console.log(green("Generated Gemfile at the repository root."));
    }
  }

  console.log(green("Scaffolded Android CI: debug APK and production release options."));
  console.log(green("The generated android/ directory remains ephemeral and does not need to be committed."));
}
